export const dictionaries: Record<Locale, Dict> = {
  en,
  ro,
  de,
  hu,
  fr,
  es,
  it,
};

export function isLocale(value: string | null | undefined): value is Locale {
  return !!value && (LOCALES as readonly string[]).includes(value);
}

export function t(locale: Locale, key: string): string {
  return dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
}

export function missingKeys(locale: Locale): string[] {
  const base = Object.keys(dictionaries.en);
  const dict = dictionaries[locale];
  return base.filter((k) => !dict[k] || dict[k] === "");
}

export function extraKeys(locale: Locale): string[] {
  const base = new Set(Object.keys(dictionaries.en));
  return Object.keys(dictionaries[locale]).filter((k) => !base.has(k));
}
